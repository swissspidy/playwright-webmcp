/**
 * Generates `docs/rules/` from the rules themselves.
 *
 *   node scripts/gen-rule-docs.mjs            write the pages
 *   node scripts/gen-rule-docs.mjs --check    exit 1 if the pages are stale
 *
 * Every fact on a page — severity, scope, whether it is on by default, its
 * options and their defaults — is read from the rule at run time, so a page
 * cannot describe a rule the code does not have. Prose that is not derivable
 * this way belongs in the READMEs, which these pages link to rather than
 * duplicate.
 *
 * Reads the built packages, so run `pnpm run build` first.
 */

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "docs", "rules");
const REPO = "https://github.com/swissspidy/playwright-webmcp";
const BANNER = "<!-- Generated by scripts/gen-rule-docs.mjs. Run `pnpm run docs:rules` after changing a rule. -->";
const check = process.argv.includes("--check");

async function load(specifier, hint) {
  try {
    return await import(specifier);
  } catch (error) {
    console.error(`Could not import ${specifier}. Run \`pnpm run build\` first.\n  ${hint}: ${error.message}`);
    process.exit(1);
  }
}

const core = await load(new URL("../packages/core/dist/index.js", import.meta.url).href, "rule engine");
const eslintMod = await load(new URL("../packages/eslint-plugin/dist/index.js", import.meta.url).href, "eslint plugin");
const plugin = eslintMod.default ?? eslintMod;

/** Markdown table cells cannot contain a raw pipe or newline. */
const cell = (text) =>
  String(text)
    .replace(/\|/g, "\\|")
    .replace(/\s*\n\s*/g, " ");
/** Short scalars read better inline; a long regex needs its own block. */
const INLINE_MAX = 60;
const inline = (value) => {
  const json = JSON.stringify(value);
  return json.length <= INLINE_MAX ? `\`${json}\`` : null;
};

const coreRules = [...core.builtinRules].sort((a, b) => a.id.localeCompare(b.id));
const eslintRules = Object.entries(plugin.rules ?? {});
const coreIds = new Set(coreRules.map((r) => r.id));
const eslintOnly = eslintRules.filter(([id]) => !coreIds.has(id)).sort(([a], [b]) => a.localeCompare(b));
const recommended = new Set(Object.keys(plugin.configs?.recommended?.rules ?? {}).map((k) => k.replace(/^webmcp\//, "")));
const inEslint = new Set(eslintRules.map(([id]) => id));

function optionsSection(defaults) {
  const entries = Object.entries(defaults ?? {});
  if (entries.length === 0) return "";
  const rows = entries.map(([name, value]) => `| \`${name}\` | ${inline(value) ?? "see below"} |`);
  const blocks = entries
    .filter(([, value]) => inline(value) === null)
    .map(
      ([name, value]) =>
        `\n<details>\n<summary><code>${name}</code> default</summary>\n\n\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\`\n\n</details>\n`,
    );
  return ["", "## Options", "", "| Option | Default |", "| --- | --- |", ...rows, ...blocks].join("\n");
}

/**
 * Show a real default in the options snippet where one is short enough to read,
 * so the line can be copied and edited rather than retyped from the table.
 */
function optionExample(rule) {
  const entries = Object.entries(rule.defaults ?? {});
  if (entries.length === 0) return [];
  const short = entries.find(([, value]) => inline(value) !== null) ?? entries[0];
  const [name, value] = short;
  const shown = inline(value) === null ? "/* see the table above */" : JSON.stringify(value);
  return [`lint(snapshot, { rules: { "${rule.id}": { ${name}: ${shown} } } });`];
}

function corePage(rule) {
  const scope = rule.scope ?? "tool";
  const eslintName = inEslint.has(rule.id) ? `webmcp/${rule.id}` : null;
  const lines = [
    BANNER,
    "",
    `# \`${rule.id}\``,
    "",
    `**${scope === "page" ? "Page" : "Tool"} rule** · \`${rule.severity}\` · ${rule.enabled ? "on by default" : "**off by default**, enable it to use it"}`,
    "",
    rule.description,
    "",
    scope === "page"
      ? "A page rule judges the tool surface as a whole, so it needs a full snapshot: the Playwright fixture, the audit crawler, or `lint()` over a snapshot you collected yourself. Static analysis of a single `registerTool()` call cannot run it."
      : "A tool rule judges one tool from its own definition, so it runs everywhere: `lint()`, `lintTools()`, the CLI, the Playwright fixture, the audit crawler and the ESLint plugin.",
    optionsSection(rule.defaults),
    "",
    "## Configuring it",
    "",
    "```ts",
    `lint(snapshot, { rules: { "${rule.id}": false } });          // off`,
    `lint(snapshot, { rules: { "${rule.id}": "warning" } });      // change severity`,
    ...optionExample(rule),
    "```",
    "",
    "```bash",
    `npx @swissspidy/webmcp-lint tools.json --rule ${rule.id}=off`,
    "```",
    ...(eslintName ? ["", "```js", "// eslint.config.js", `{ rules: { "${eslintName}": "error" } }`, "```"] : []),
    "",
    "---",
    "",
    `[All rules](./README.md) · [Rule reference in the README](${REPO}#rules)`,
    "",
  ];
  return lines.join("\n");
}

function eslintPage(id, rule) {
  const docs = rule.meta?.docs ?? {};
  const hasOptions = Array.isArray(rule.meta?.schema) && rule.meta.schema.length > 0;
  return [
    BANNER,
    "",
    `# \`webmcp/${id}\``,
    "",
    `**ESLint-only rule** · \`${rule.meta?.type ?? "suggestion"}\` · ${recommended.has(id) ? "in `recommended`" : "not in `recommended`, in `all`"}`,
    "",
    docs.description ?? "",
    "",
    "This rule has no counterpart in the `@swissspidy/webmcp-lint` engine: it reads the source, and what it catches does not survive to runtime for a page rule to see.",
    "",
    "## Configuring it",
    "",
    "```js",
    "// eslint.config.js",
    `{ rules: { "webmcp/${id}": ${hasOptions ? '["warn", { /* options */ }]' : '"warn"'} } }`,
    "```",
    "",
    "---",
    "",
    `[All rules](./README.md) · [Plugin README](${REPO}/tree/main/packages/eslint-plugin#readme)`,
    "",
  ].join("\n");
}

function index() {
  const tool = coreRules.filter((r) => (r.scope ?? "tool") !== "page");
  const page = coreRules.filter((r) => (r.scope ?? "tool") === "page");
  const row = (r) => `| [\`${r.id}\`](./${r.id}.md) | \`${r.severity}\` | ${r.enabled ? "on" : "off"} | ${cell(r.description)} |`;
  return [
    BANNER,
    "",
    "# Rules",
    "",
    `${coreRules.length + eslintOnly.length} rules: ${coreRules.length} from the \`@swissspidy/webmcp-lint\` engine and ${eslintOnly.length} that exist only as ESLint rules.`,
    "",
    "Every page here is generated from the rule itself, so the severities, defaults and options on them are the ones the code actually uses.",
    "",
    `## Tool rules (${tool.length})`,
    "",
    "Judge one tool from its own definition. They run in the engine, the CLI, the Playwright fixture, the audit crawler, and — as `webmcp/<id>` — in the ESLint plugin.",
    "",
    "| Rule | Severity | Default | What it catches |",
    "| --- | --- | --- | --- |",
    ...tool.map(row),
    "",
    `## Page rules (${page.length})`,
    "",
    "Judge the tool surface as a whole, so they need a full snapshot and have no ESLint equivalent.",
    "",
    "| Rule | Severity | Default | What it catches |",
    "| --- | --- | --- | --- |",
    ...page.map(row),
    "",
    `## ESLint-only rules (${eslintOnly.length})`,
    "",
    "Read the source rather than a tool definition, so they have no engine counterpart.",
    "",
    "| Rule | Type | In `recommended` | What it catches |",
    "| --- | --- | --- | --- |",
    ...eslintOnly.map(
      ([id, r]) =>
        `| [\`webmcp/${id}\`](./${id}.md) | \`${r.meta?.type ?? "suggestion"}\` | ${recommended.has(id) ? "yes" : "no"} | ${cell(r.meta?.docs?.description ?? "")} |`,
    ),
    "",
  ].join("\n");
}

const raw = new Map([
  ["README.md", index()],
  ...coreRules.map((r) => [`${r.id}.md`, corePage(r)]),
  ...eslintOnly.map(([id, r]) => [`${id}.md`, eslintPage(id, r)]),
]);

// Format with the repository's own prettier config. Without this, `pnpm run
// format` would rewrite these pages and the --check below would then call them
// stale, so the two would fight every time anyone formatted the tree.
const prettierConfig = await prettier.resolveConfig(path.join(OUT, "README.md"));
const pages = new Map();
for (const [name, body] of raw) {
  pages.set(name, await prettier.format(body, { ...prettierConfig, parser: "markdown" }));
}

// Every `meta.docs.url` an editor might open has to land on a page that exists.
// This catches an ESLint rule added without a counterpart page, which no amount
// of comparing file contents would notice.
const dangling = eslintRules.map(([id, rule]) => [id, rule.meta?.docs?.url]).filter(([, url]) => !url || !pages.has(url.split("/").pop()));
if (dangling.length) {
  console.error("These ESLint rules point at a documentation page that is not generated:");
  for (const [id, url] of dangling) console.error(`  ${id} -> ${url ?? "(no url)"}`);
  process.exit(1);
}

if (check) {
  const existing = await readdir(OUT).catch(() => []);
  const stale = [...existing].filter((f) => f.endsWith(".md") && !pages.has(f));
  const wrong = [];
  for (const [name, body] of pages) {
    const current = await readFile(path.join(OUT, name), "utf8").catch(() => null);
    if (current !== body) wrong.push(name);
  }
  if (wrong.length || stale.length) {
    console.error("docs/rules is out of date. Run `pnpm run docs:rules` and commit the result.");
    for (const f of wrong) console.error(`  changed or missing: ${f}`);
    for (const f of stale) console.error(`  no longer a rule:   ${f}`);
    process.exit(1);
  }
  console.log(`docs/rules is up to date (${pages.size} pages).`);
} else {
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });
  for (const [name, body] of pages) await writeFile(path.join(OUT, name), body);
  console.log(`Wrote ${pages.size} pages to docs/rules.`);
}
